const TEXTOS = { es, en };
export const IDIOMAS = Object.keys(TEXTOS);
const CLAVE = 'idioma';

function inicial() {
  try {
    const guardado = localStorage.getItem(CLAVE);
    if (TEXTOS[guardado]) return guardado;
  } catch {}
  if (TEXTOS[IDIOMA_INICIAL]) return IDIOMA_INICIAL;
  const navegador = (typeof navigator !== 'undefined' && navigator.language || '').slice(0, 2);
  return TEXTOS[navegador] ? navegador : 'es';
}

let actual = inicial();
const oyentes = new Set();
if (typeof document !== 'undefined') document.documentElement.lang = actual;

// t('clave') o t('clave', { n: 3 }). Si falta en un idioma, usa el español.
export function t(clave, valores = {}) {
  const texto = TEXTOS[actual][clave] ?? TEXTOS.es[clave] ?? clave;
  return typeof texto === 'function' ? texto(valores) : texto;
}

export const idiomaActual = () => actual;

export function cambiarIdioma(nuevo) {
  if (!TEXTOS[nuevo] || nuevo === actual) return;
  actual = nuevo;
  try { localStorage.setItem(CLAVE, nuevo); } catch {}
  document.documentElement.lang = nuevo;
  oyentes.forEach((o) => o());
}

// Quien usa este hook se vuelve a pintar al cambiar el idioma (con él, todo lo de adentro)
export const useIdioma = () => useSyncExternalStore((o) => { oyentes.add(o); return () => oyentes.delete(o); }, () => actual);
